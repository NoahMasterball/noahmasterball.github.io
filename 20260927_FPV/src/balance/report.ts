function formatValue(v: unknown): string {
  if (v === null) return 'none';
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(Number(v.toFixed(3)));
  if (typeof v === 'object') {
    const entries = Object.entries(v as Record<string, unknown>);
    return entries.length ? entries.map(([k, x]) => `${k} ×${formatValue(x)}`).join(', ') : '–';
  }
  return String(v);
}

/** Keys naming the variant of a tagged data object (activations, resources, effects, triggers:
 *  `kind`; bot hints: `use`). */
const TAG_KEYS: readonly string[] = ['kind', 'use'];

const isTagged = (v: unknown): v is object => typeof v === 'object' && v !== null && TAG_KEYS.some((k) => k in v);

/** A tagged data object as text: its tag, then its parameters; a nested tagged object reads the
 *  same way (`trigger proximity (radius 1.2)`). */
function describe(o: object): string {
  const entries = Object.entries(o);
  const tag = String(entries.find(([k]) => TAG_KEYS.includes(k))?.[1]);
  const params = entries
    .filter(([k]) => !TAG_KEYS.includes(k))
    .map(([k, v]) => `${k} ${isTagged(v) ? describe(v) : formatValue(v)}`);
  return params.length ? `${tag} (${params.join('; ')})` : tag;
}

const effectsText = (effects: readonly EffectDef[]): string => effects.map(describe).join(' + ');
const abilityNames = (ids: readonly string[]): string => ids.map((id) => getAbility(id).name).join(', ');
const weaponNames = (ids: readonly string[]): string =>
  ids.map((id) => WEAPONS.find((w) => w.id === id)?.name ?? id).join(' / ');

function abilityRow(a: AbilityDef): string[] {
  return [
    a.name,
    describe(a.activation),
    describe(a.resource),
    effectsText(a.effects),
    String(a.budgetCost),
    describe(a.bot),
  ];
}

export function rosterMarkdown(): string {
  const operators = table(
    ['Operator', 'Archetype', 'HP', 'Armour', 'Hitbox', 'Speed', 'Sprint ×', 'Accel', 'Crouch', 'Jump', 'ADS move ×', 'Abilities', 'Primary', 'Secondary'],
    OPERATORS.map((o) => [
      o.name,
      o.archetype,
      String(o.maxHealth),
      formatValue(o.armour),
      o.hitboxProfile,
      formatValue(o.moveSpeed),
      formatValue(o.sprintMultiplier),
      formatValue(o.acceleration),
      formatValue(o.crouchSpeed),
      formatValue(o.jumpHeight),
      formatValue(o.adsMovePenalty),
      abilityNames(o.abilities),
      weaponNames(o.loadout.primary),
      weaponNames(o.loadout.secondary),
    ]),
  );
  const bios = OPERATORS.map((o) => `- **${o.name}** — ${o.presentation.bio} *Silhouette:* ${o.presentation.silhouette}`);
  const weapons = table(
    ['Weapon', 'Class', 'Mode', 'Damage', 'Falloff (m → min)', 'Pellets', 'RPM', 'Mag', 'Reserve', 'Reload s', 'Hip°', 'ADS°', '+/shot°', 'Move°', 'Max°', 'ADS s', 'ADS FOV ×', 'Head ×', 'Limb ×', 'Move ×'],
    WEAPONS.map((w) => [
      w.name,
      w.class,
      w.fireMode,
      String(w.damage),
      `${w.falloff.start}–${w.falloff.end} → ${w.falloff.minDamage}`,
      String(w.pellets),
      String(w.rpm),
      String(w.magazine),
      String(startingReserve(w)),
      formatValue(w.reloadTime),
      formatValue(w.hipSpread),
      formatValue(w.adsSpread),
      formatValue(w.spreadPerShot),
      formatValue(w.spreadMoving),
      formatValue(w.maxSpread),
      formatValue(w.adsTime),
      formatValue(w.adsFovMultiplier),
      formatValue(w.headshotMultiplier),
      formatValue(w.limbMultiplier),
      formatValue(w.moveSpeedModifier),
    ]),
  );
  const abilities = table(['Ability', 'Activation', 'Resource', 'Effects', 'Budget', 'Bots'], ABILITIES.map(abilityRow));
  return [
    '# Roster',
    '',
    GENERATED_NOTE,
    '',
    'Units: HP, m/s, m/s², m, seconds, degrees. Identity and intent: [SPEC §10](../SPEC.md#10-archetypes-and-example-roster).',
    '',
    '## Operators',
    '',
    operators,
    '',
    ...bios,
    '',
    '## Weapons',
    '',
    weapons,
    '',
    'Recoil patterns are per-shot arrays in `src/data/weapons.ts`.',
    '',
    '## Abilities',
    '',
    '"Bots" = when bots use the ability (`AbilityDef.bot`, ADR-0012 §10); without `maxRangeM` a bot uses its derived reach.',
    '',
    abilities,
    '',
  ].join('\n');
}
