// NEW — Markdown renderers for the generated balance and roster documents (ADR-0010).
// Pure string builders: used by tools/balance.ts, tools/gen-docs.ts and the docs-sync test.

const GENERATED_NOTE = '> Generated by `npm run docs:gen` from `src/data/` — do not edit by hand.';

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]): string => `| ${cells.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n');
}

const num = (v: number, digits = 1): string => (Number.isFinite(v) ? v.toFixed(digits) : '∞');
const signed = (v: number): string => `${v >= 0 ? '+' : ''}${v.toFixed(2)}`;
const ms = (seconds: number): string => (Number.isFinite(seconds) ? String(Math.round(seconds * 1000)) : '∞');

export function budgetMarkdown(): string {
  const rows = OPERATORS.map((op) => {
    const b = operatorBudget(op);
    return [
      op.name,
      op.archetype,
      num(b.effectiveHp, 0),
      num(b.exposure, 2),
      signed(b.survivability),
      signed(b.mobility),
      signed(b.firepower),
      signed(b.utility),
      `**${b.total.toFixed(2)}**`,
      budgetStatus(b.total),
    ];
  });
  return [
    `Target band: ${BUDGET.target} ± ${BUDGET.tolerance} points. Categories are relative to the reference ` +
      `operator/weapon in \`src/data/budget.ts\` (0 = reference).`,
    '',
    table(['Operator', 'Archetype', 'Eff. HP', 'Exposure', 'Surv.', 'Mob.', 'Fire', 'Util.', 'Total', 'Status'], rows),
  ].join('\n');
}

export function ttkMarkdown(): string {
  const parts: string[] = [
    'Milliseconds from first to killing shot, `body / head`, every shot landing, full magazine at start, ' +
      'reload included when the magazine runs dry, all pellets hitting.',
  ];
  for (const t of ttkMatrix(BALANCE_REPORT.ttkRanges)) {
    const rows = WEAPONS.map((w) => [
      `${w.name} (${w.class})`,
      ...OPERATORS.map((op) => {
        const c = t.cells.get(w.id)?.get(op.id);
        return c ? `${ms(c.body.seconds)} / ${ms(c.head.seconds)}` : '–';
      }),
    ]);
    parts.push('', `### ${t.range} m`, '', table(['Weapon', ...OPERATORS.map((o) => o.name)], rows));
  }
  return parts.join('\n');
}

export function balanceMarkdown(): string {
  return [
    '# Balance report',
    '',
    GENERATED_NOTE,
    '',
    '## Power budget',
    '',
    budgetMarkdown(),
    '',
    '## Time-to-kill matrix',
    '',
    ttkMarkdown(),
    '',
  ].join('\n');
}

